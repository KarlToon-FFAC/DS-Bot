import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = join(import.meta.dirname, 'probe-plugin')
const result = await build({ entryPoints: [join(dir, 'client-source.js')], bundle: true, format: 'cjs',
  platform: 'browser', target: 'es2022', external: ['react', 'react-dom'], charset: 'utf8', write: false })
const text = `// Generated by node dev/communication/build-probe.mjs.\nwindow.__ModuleLoader__.load({id:'ds-bot-communication-probe',factory:(require)=>{const module={exports:{}};\n${result.outputFiles[0].text}\nreturn Object.defineProperty({...module.exports},Symbol.toStringTag,{value:'Module'})}})\n`
if (process.argv.includes('--check')) {
  if (readFileSync(join(dir, 'client.js'), 'utf8') !== text) throw new Error('P0 client is stale: run node dev/communication/build-probe.mjs')
} else writeFileSync(join(dir, 'client.js'), text)
